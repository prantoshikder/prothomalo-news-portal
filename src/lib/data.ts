function readMinutesFor(text: string) {
  return Math.max(2, Math.round(text.split(/\s+/).length / 120) + 2);
}

export const articles: Article[] = seeds
  .map((s, i): Article => {
    const [slug, title, excerpt, category, author, publishedAt, location, tags, views, isVideo] = s;
    const body = [excerpt, ...bodyByCategory[category], ...closingParagraphs];
    return {
      id: i + 1,
      slug,
      title,
      excerpt,
      category,
      author: reporters[author],
      publishedAt,
      readMinutes: readMinutesFor(body.join(" ")),
      imageSeed: `nk-${slug}`,
      imageCaption: `${location} — প্রতীকী ছবি`,
      tags,
      views,
      location,
      isVideo,
      body,
    };
  })
  .sort((a, b) => Date.parse(b.publishedAt) - Date.parse(a.publishedAt));

