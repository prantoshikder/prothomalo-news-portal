export function getCategory(slug: string) {
  return categories.find((c) => c.slug === slug);
}

export function getArticle(slug: string) {
  return articles.find((a) => a.slug === slug);
}

export function getArticlesByCategory(slug: CategorySlug, limit?: number) {
  const list = articles.filter((a) => a.category === slug);
  return limit ? list.slice(0, limit) : list;
}

export function getLatest(limit = 10) {
  return articles.slice(0, limit);
}

export function getMostRead(limit = 10) {
  return [...articles].sort((a, b) => b.views - a.views).slice(0, limit);
}

export function getVideos() {
  return articles.filter((a) => a.isVideo);
}

export function getRelated(article: Article, limit = 4) {
  const sameCat = articles.filter(
    (a) => a.category === article.category && a.slug !== article.slug,
  );
  const sharedTag = articles.filter(
    (a) =>
      a.category !== article.category &&
      a.tags.some((t) => article.tags.includes(t)),
  );
  return [...sameCat, ...sharedTag].slice(0, limit);
}

export function searchArticles(query: string) {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return articles.filter(
    (a) =>
      a.title.toLowerCase().includes(q) ||
      a.excerpt.toLowerCase().includes(q) ||
      a.tags.some((t) => t.toLowerCase().includes(q)) ||
      a.location.toLowerCase().includes(q),
  );
}

export function getAllTags() {
  const counts = new Map<string, number>();
  for (const a of articles) for (const t of a.tags) counts.set(t, (counts.get(t) ?? 0) + 1);
  return [...counts.entries()].sort((a, b) => b[1] - a[1]).map(([t]) => t);
}

